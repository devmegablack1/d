static inline void putpx(u16 *fb, int x, int y, u16 c)
{
    if ((unsigned)x < SW && (unsigned)y < SH) fb[y * SW + x] = c;
}

static void fill_rect(u16 *fb, int x, int y, int w, int h, u16 c)
{
    int x1 = x + w, y1 = y + h;
    if (x < 0) x = 0;
    if (y < 0) y = 0;
    if (x1 > SW) x1 = SW;
    if (y1 > SH) y1 = SH;
    for (int j = y; j < y1; j++) {
        u16 *p = fb + j * SW + x;
        for (int i = x; i < x1; i++) *p++ = c;
    }
}

static int circ_dx(int r, int dy)
{
    int dx = 0;
    while ((dx + 1) * (dx + 1) + dy * dy <= r * r + r) dx++;
    return dx;
}

static void fill_circle(u16 *fb, int cx, int cy, int r, u16 c)
{
    for (int dy = -r; dy <= r; dy++) {
        int dx = circ_dx(r, dy);
        fill_rect(fb, cx - dx, cy + dy, 2 * dx + 1, 1, c);
    }
}

static void fill_rrect(u16 *fb, int x, int y, int w, int h, int r, u16 c)
{
    if (r * 2 > h) r = h / 2;
    if (r * 2 > w) r = w / 2;
    for (int j = 0; j < h; j++) {
        int inset = 0;
        if (j < r)          inset = r - circ_dx(r, r - j - 1) ;
        else if (j >= h - r) inset = r - circ_dx(r, j - (h - r));
        if (inset < 0) inset = 0;
        fill_rect(fb, x + inset, y + j, w - 2 * inset, 1, c);
    }
}

// right-pointing triangle in a w*h box
static void tri_right(u16 *fb, int x, int y, int w, int h, u16 c)
{
    for (int i = 0; i < w; i++) {
        int span = h * (w - i) / w;
        if (span < 1) span = 1;
        fill_rect(fb, x + i, y + (h - span) / 2, 1, span, c);
    }
}
static void tri_left(u16 *fb, int x, int y, int w, int h, u16 c)
{
    for (int i = 0; i < w; i++) {
        int span = h * (i + 1) / w;
        fill_rect(fb, x + i, y + (h - span) / 2, 1, span, c);
    }
}
static void tri_up(u16 *fb, int x, int y, int w, int h, u16 c)
{
    for (int j = 0; j < h; j++) {
        int span = w * (j + 1) / h;
        fill_rect(fb, x + (w - span) / 2, y + j, span, 1, c);
    }
}
static void tri_down(u16 *fb, int x, int y, int w, int h, u16 c)
{
    for (int j = 0; j < h; j++) {
        int span = w * (h - j) / h;
        fill_rect(fb, x + (w - span) / 2, y + j, span, 1, c);
    }
}

// thick line made of small squares (only used for the note beam)
static void thick_line(u16 *fb, int x0, int y0, int x1, int y1, int th, u16 c)
{
    int dx = x1 - x0, steps = dx < 0 ? -dx : dx;
    if (steps == 0) steps = 1;
    for (int i = 0; i <= steps; i++) {
        int x = x0 + dx * i / steps;
        int y = y0 + (y1 - y0) * i / steps;
        fill_rect(fb, x, y, 1, th, c);
    }
}

// ------------------------------------------------------------ text

static inline u16 blend(u16 bg, u16 fg, int a)      // a: 0..255
{
    a += a >> 7;                                     // 0..256
    int br = bg & 31, bgc = (bg >> 5) & 31, bb = (bg >> 10) & 31;
    int fr = fg & 31, fgc = (fg >> 5) & 31, fb = (fg >> 10) & 31;
    int r = (br  * (256 - a) + fr  * a) >> 8;
    int g = (bgc * (256 - a) + fgc * a) >> 8;
    int b = (bb  * (256 - a) + fb  * a) >> 8;
    return (u16)(0x8000 | r | (g << 5) | (b << 10));
}

static int glyph_index(int ch)
{
    if (ch < 32 || ch > 126) return '?' - 32;
    return ch - 32;
}

// Next character of a UTF-8 string as plain ASCII (accents are dropped).
static int next_char(const char **ps)
{
    unsigned char c = (unsigned char)**ps;
    if (!c) return 0;
    (*ps)++;
    if (c < 0x80) return c;

    int extra = (c & 0xE0) == 0xC0 ? 1 : (c & 0xF0) == 0xE0 ? 2 : (c & 0xF8) == 0xF0 ? 3 : 0;
    unsigned char first = 0;
    for (int i = 0; i < extra; i++) {
        unsigned char d = (unsigned char)**ps;
        if ((d & 0xC0) != 0x80) break;
        if (i == 0) first = d;
        (*ps)++;
    }
    if (c == 0xC3 && first >= 0x80) {
        int l = 0xC0 + (first - 0x80);              // Latin-1 code point
        if (l == 0xDF) return 's';                  // sharp s
        if (l == 0xD7 || l == 0xF7) return '?';
        int low = l >= 0xE0;
        int b = low ? l - 0x20 : l;
        int up = '?';
        if (b <= 0xC6) up = 'A';
        else if (b == 0xC7) up = 'C';
        else if (b <= 0xCB) up = 'E';
        else if (b <= 0xCF) up = 'I';
        else if (b == 0xD0) up = 'D';
        else if (b == 0xD1) up = 'N';
        else if (b <= 0xD6 || b == 0xD8) up = 'O';
        else if (b <= 0xDC) up = 'U';
        else if (b == 0xDD) up = 'Y';
        if (up == '?') return '?';
        return low ? up + 32 : up;
    }
    return '?';
}

static int text_width(const Font *f, const char *s)
{
    int w = 0, ch;
    while ((ch = next_char(&s)) != 0) w += f->g[glyph_index(ch)].adv;
    return w;
}

static void draw_text(u16 *fb, const Font *f, int x, int y, const char *s, u16 col)
{
    int ch;
    while ((ch = next_char(&s)) != 0) {
        const FGlyph *g = &f->g[glyph_index(ch)];
        const unsigned char *d = f->d + g->off;
        for (int j = 0; j < g->h; j++) {
            int py = y + g->yo + j;
            if ((unsigned)py >= SH) continue;
            for (int i = 0; i < g->w; i++) {
                unsigned a = d[j * g->w + i];
                if (!a) continue;
                int px = x + g->xo + i;
                if ((unsigned)px >= SW) continue;
                u16 *p = &fb[py * SW + px];
                *p = (a >= 250) ? col : blend(*p, col, (int)a);
            }
        }
        x += g->adv;
    }
}

// Copy src into dst, shortening with "..." so it fits in maxw pixels.
static void fit_text(char *dst, size_t cap, const Font *f, const char *src, int maxw)
{
    strncpy(dst, src, cap - 1);
    dst[cap - 1] = 0;
    if (text_width(f, dst) <= maxw) return;
    size_t n = strlen(dst);
    while (n > 0) {
        n--;
        dst[n] = 0;
        char tmp[NAME_LEN + 4];
        size_t m = n;
        while (m > 0 && dst[m - 1] == ' ') m--;
        memcpy(tmp, dst, m);
        strcpy(tmp + m, "...");
        if (text_width(f, tmp) <= maxw) { strcpy(dst, tmp); return; }
    }
}

static void draw_text_right(u16 *fb, const Font *f, int xr, int y, const char *s, u16 col)
{
    draw_text(fb, f, xr - text_width(f, s), y, s, col);
}

