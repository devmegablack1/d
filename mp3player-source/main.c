static void draw_cover(u16 *fb, int x0, int y0, int s)
{
    int pic = (sh_s > 0 && nfiles > 0);
    if (s > 96) s = 96;
    if (x0 < 0 || y0 < 0 || x0 + s > SW || y0 + s > SH) return;
    int xs[96];
    u16 gt[192];
    if (pic) for (int i = 0; i < s; i++) xs[i] = i * sh_s / s;
    else     for (int d = 0; d < 2 * s; d++) gt[d] = lerp3(cov1, cov2, d * 256 / (2 * s));
    mark(fb, y0, y0 + s);
    for (int j = 0; j < s; j++) {
        u16 *dst = fb + (y0 + j) * SW + x0;
        if (pic) {
            const u16 *src = sh_pix + (j * sh_s / s) * sh_s;
            for (int i = 0; i < s; i++) dst[i] = src[xs[i]];
        } else {
            for (int i = 0; i < s; i++) dst[i] = gt[i + j];
        }
    }
    // round the corners by painting the screen background back
    int r = 8;
    for (int k = 0; k < r; k++) {
        int inset = r - circ_dx(r, r - k - 1);
        for (int i = 0; i < inset; i++) {
            putpx(fb, x0 + i, y0 + k, top_bg(y0 + k));
            putpx(fb, x0 + s - 1 - i, y0 + k, top_bg(y0 + k));
            putpx(fb, x0 + i, y0 + s - 1 - k, top_bg(y0 + s - 1 - k));
            putpx(fb, x0 + s - 1 - i, y0 + s - 1 - k, top_bg(y0 + s - 1 - k));
        }
    }
    if (pic) return;

    // beamed music note on the generated cover
    u16 w = RGB(255, 255, 255);
    int sc = s;
    int h1x = x0 + sc * 30 / 96, h1y = y0 + sc * 68 / 96;
    int h2x = x0 + sc * 62 / 96, h2y = y0 + sc * 60 / 96;
    int hr  = sc * 10 / 96;
    fill_circle(fb, h1x, h1y, hr, w);
    fill_circle(fb, h2x, h2y, hr, w);
    int sw = sc * 4 / 96 + 1;
    fill_rect(fb, h1x + hr - sw, y0 + sc * 28 / 96, sw, h1y - (y0 + sc * 28 / 96), w);
    fill_rect(fb, h2x + hr - sw, y0 + sc * 20 / 96, sw, h2y - (y0 + sc * 20 / 96), w);
    thick_line(fb, h1x + hr - sw, y0 + sc * 28 / 96, h2x + hr, y0 + sc * 20 / 96, sc * 7 / 96 + 1, w);
}

static unsigned elapsed_sec(void)
{
    unsigned sec = playing ? (unsigned)(samples_out / (unsigned)hz) : 0;
    if (total_sec > 0 && sec > total_sec) sec = total_sec;
    return sec;
}

static unsigned elapsed_ms(void)
{
    if (!playing || hz <= 0) return 0;
    unsigned long long so = samples_out;
    return (unsigned)(so / (unsigned)hz) * 1000u + (unsigned)((so % (unsigned)hz) * 1000u / (unsigned)hz);
}

