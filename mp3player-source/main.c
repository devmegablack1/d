static inline u16 blend(u16 bg, u16 fg, int a)      // a: 0..255
{
    a += a >> 7;                                     // 0..256
    int br = bg & 31, bgc = (bg >> 5) & 31, bb = (bg >> 10) & 31;
    int fr = fg & 31, fgc = (fg >> 5) & 31, fb = (fg >> 10) & 31;
    int r = (br  * (256 - a) + fr  * a) >> 8;
    int g = (bgc * (256 - a) + fgc * a) >> 8;
    int b = (bb  * (256 - a) + fb  * a) >> 8;
    return (u16)(0x8000 | r | (g << 5) | (b << 10));
}

static int glyph_index(int ch)
{
    if (ch < 32 || ch > 126) return '?' - 32;
    return ch - 32;
}

// Next character of a UTF-8 string as plain ASCII (accents are dropped).
static const char latx[] = "AaAaAaCcCcCcCcDdDdEeEeEeEeEeGgGgGgGgHhHhIiIiIiIiIiIiJjKkkLlLlLl??LlNnNnNnnNnOoOoOoOoRrRrRrSsSsSsSsTtTtTtUuUuUuUuUuUuWwYyYZzZzZzs";   // U+0100 .. U+017F

static int next_char(const char **ps)
{
    unsigned char c = (unsigned char)**ps;
    if (!c) return 0;
    (*ps)++;
    if (c < 0x80) return c;

    int extra = (c & 0xE0) == 0xC0 ? 1 : (c & 0xF0) == 0xE0 ? 2 : (c & 0xF8) == 0xF0 ? 3 : 0;
    unsigned cp = extra == 1 ? (c & 0x1Fu) : extra == 2 ? (c & 0x0Fu) : extra == 3 ? (c & 7u) : 0;
    int got = 0;
    for (int i = 0; i < extra; i++) {
        unsigned char d = (unsigned char)**ps;
        if ((d & 0xC0) != 0x80) break;
        cp = (cp << 6) | (d & 63u);
        (*ps)++;
        got++;
    }
    if (extra == 0 || got != extra) return '?';

    if (cp == 0xA0) return ' ';
    if (cp >= 0xC0 && cp <= 0xFF) {
        int l = (int)cp;                           // Latin-1 letter
        if (l == 0xDF) return 's';                 // sharp s
        if (l == 0xD7 || l == 0xF7) return '?';
        int low = l >= 0xE0;
        int b = low ? l - 0x20 : l;
        int up = '?';
        if (b <= 0xC6) up = 'A';
        else if (b == 0xC7) up = 'C';
        else if (b <= 0xCB) up = 'E';
        else if (b <= 0xCF) up = 'I';
        else if (b == 0xD0) up = 'D';
        else if (b == 0xD1) up = 'N';
        else if (b <= 0xD6 || b == 0xD8) up = 'O';
        else if (b <= 0xDC) up = 'U';
        else if (b == 0xDD) up = 'Y';
        if (up == '?') return '?';
        return low ? up + 32 : up;
    }
    if (cp >= 0x100 && cp <= 0x17F) return latx[cp - 0x100];
    if ((cp >= 0x2010 && cp <= 0x2015) || cp == 0x2212) return '-';
    if (cp == 0x2018 || cp == 0x2019 || cp == 0x201A || cp == 0xB4) return '\'';
    if (cp == 0x201C || cp == 0x201D || cp == 0x201E) return '"';
    if (cp == 0x2026 || cp == 0x2022 || cp == 0xB7) return '.';
    return '?';
}

static int text_width(const Font *f, const char *s)
{
    int w = 0, ch;
    while ((ch = next_char(&s)) != 0) w += f->g[glyph_index(ch)].adv;
    return w;
}

static void draw_text(u16 *fb, const Font *f, int x, int y, const char *s, u16 col)
{
    int ch;
    mark(fb, y - 2, y + f->lh + 4);
    while ((ch = next_char(&s)) != 0) {
        const FGlyph *g = &f->g[glyph_index(ch)];
        const unsigned char *d = f->d + g->off;
        for (int j = 0; j < g->h; j++) {
            int py = y + g->yo + j;
            if ((unsigned)py >= SH) continue;
            for (int i = 0; i < g->w; i++) {
                unsigned a = d[j * g->w + i];
                if (!a) continue;
                int px = x + g->xo + i;
                if ((unsigned)px >= SW) continue;
                u16 *p = &fb[py * SW + px];
                *p = (a >= 250) ? col : blend(*p, col, (int)a);
            }
        }
        x += g->adv;
    }
}

// Copy src into dst, shortening with "..." so it fits in maxw pixels.
static void fit_text(char *dst, size_t cap, const Font *f, const char *src, int maxw)
{
    strncpy(dst, src, cap - 1);
    dst[cap - 1] = 0;
    if (text_width(f, dst) <= maxw) return;
    size_t n = strlen(dst);
    while (n > 0) {
        n--;
        dst[n] = 0;
        char tmp[NAME_LEN + 4];
        size_t m = n;
        while (m > 0 && dst[m - 1] == ' ') m--;
        memcpy(tmp, dst, m);
        strcpy(tmp + m, "...");
        if (text_width(f, tmp) <= maxw) { strcpy(dst, tmp); return; }
    }
}

static void draw_text_right(u16 *fb, const Font *f, int xr, int y, const char *s, u16 col)
{
    draw_text(fb, f, xr - text_width(f, s), y, s, col);
}

