// ------------------------------------------------------------ main

static void refresh_all(void)
{
    cover_changed = 0;
    pick_colours();
    draw_top_full();
    draw_bottom_full();
}

int main(int argc, char **argv)
{
    videoSetMode(MODE_5_2D | DISPLAY_BG3_ACTIVE);
    videoSetModeSub(MODE_5_2D | DISPLAY_BG3_ACTIVE);
    vramSetBankA(VRAM_A_MAIN_BG);
    vramSetBankC(VRAM_C_SUB_BG);
    int bgT = bgInit(3, BgType_Bmp16, BgSize_B16_256x256, 0, 0);
    int bgB = bgInitSub(3, BgType_Bmp16, BgSize_B16_256x256, 0, 0);
    vramT = (u16 *)bgGetGfxPtr(bgT);
    vramB = (u16 *)bgGetGfxPtr(bgB);

    mm_ds_system sys;
    memset(&sys, 0, sizeof sys);
#ifdef FIFO_MAXMOD
    sys.fifo_channel = FIFO_MAXMOD;
#endif
    mmInit(&sys);

    KOI_SCFG_CLK |= 1;               // DSi: 134 MHz CPU (no effect on a DS)
    time_init();

    strcpy(dirpath, "/");
    if (fatInitDefault()) {
        if (argc > 0 && argv[0]) {
            char *slash = strrchr(argv[0], '/');
            if (slash) {
                size_t len = (size_t)(slash - argv[0]);
                if (len > 0 && len < NAME_LEN - 2) {
                    memcpy(dirpath, argv[0], len);
                    dirpath[len] = 0;
                    if (dirpath[len - 1] == ':') strcat(dirpath, "/");
                }
            }
        }
        scan_library();
        if (nroot + nalb == 0) {     // launcher gave no usable path: try the working folder
            char cwd[NAME_LEN];
            if (getcwd(cwd, sizeof cwd) && strcmp(cwd, dirpath) != 0) {
                strcpy(dirpath, cwd);
                scan_library();
            }
        }
    }
    strcpy(playdir, dirpath);

    preload_covers();                // decode new icon.png files once (cached on the SD card)
    preload_library();               // tags + song pictures, so nothing has to load during playback

    refresh_all();                   // show the library before the first (slow) load
    flush_screens();
    if (nroot > 0) {                 // start playing the loose songs right away
        use_browse_as_playlist();
        open_track(0);
    }
    center_view_on_current();
    refresh_all();
    flush_screens();

    time_calibrate();                // so that animations run at true speed on any console
    unsigned now = now_ms(), t_prog = now, t_eq = now, t_viz = now, t_frame = now;
    unsigned viz_interval = 50;      // bars update 20 times a second (10 if the CPU is struggling)
    int frames = 0, slow = 0, combine = 0;

    while (pmMainLoop()) {
        mmStreamUpdate();
        swiWaitForVBlank();
        flush_screens();             // show what was drawn last pass, tear-free
        tick++;
        now = now_ms();
        vtick = now * 3u / 50u;
        {   // if many passes take longer than a frame, slow the bars down a little
            unsigned dt = now - t_frame;
            t_frame = now;
            if (dt > 24) slow++;
            if (++frames >= 60) {
                // Decoding alone takes longer than a frame: passes are long anyway, so drawing is
                // squeezed into the same pass as the decode instead of costing extra passes.
                combine = slow > 20;
                viz_interval = combine ? 100 : 50;
                frames = slow = 0;
            }
        }

        scanKeys();
        u32 down = keysDown();
        int full = 0, ctrl = 0, listd = 0, recenter = 0, topd = 0;

        if (down & KEY_A) {
            if (!playing) open_track(cur);
            else paused = !paused;
            ctrl = 1; listd = 1;
        }
        if (down & KEY_B)                { open_track(cur); full = 1; recenter = 1; }
        if (down & (KEY_R | KEY_RIGHT))  { next_track(+1);  full = 1; recenter = 1; }
        if (down & (KEY_L | KEY_LEFT))   { next_track(-1);  full = 1; recenter = 1; }
        if (down & KEY_Y)                { loop_mode = (loop_mode + 1) % 3; ctrl = 1; }
        if (down & KEY_SELECT)           { lyr_view = !lyr_view; topd = 1; ctrl = 1; }
        if (down & KEY_X)                { shuffle = !shuffle; ctrl = 1; }
        if (down & KEY_DOWN)             { view_first++; clamp_view(); listd = 1; }
        if (down & KEY_UP)               { view_first--; clamp_view(); listd = 1; }
        if ((down & KEY_START) && browse >= 0) { leave_album(); listd = 1; }

        if (down & KEY_TOUCH) {
            touchPosition t;
            touchRead(&t);
            int tx = t.px, ty = t.py;

            if (ty >= LIST_Y && ty < LIST_Y + ROWS_VIS * ROW_H) {
                int idx = view_first + (ty - LIST_Y) / ROW_H;
                if (idx >= 0 && idx < item_count()) {
                    if (browse < 0 && idx < nalb) {
                        enter_album(idx);                     // open the folder
                        listd = 1;
                    } else {
                        int si = browse < 0 ? idx - nalb : idx;
                        if (nfiles > 0 && browse == play_album && si == cur && playing) {
                            paused = !paused;                 // tap the playing song
                        } else {
                            if (browse != play_album || nfiles == 0) use_browse_as_playlist();
                            open_track(si);
                        }
                        full = 1;
                    }
                }
            } else if (ty < LIST_Y) {
                if (tx < 60 && browse >= 0)        { leave_album(); listd = 1; }
                else if (tx >= 200 && tx < 224)    { view_first -= ROWS_VIS; clamp_view(); listd = 1; }
                else if (tx >= 224)                { view_first += ROWS_VIS; clamp_view(); listd = 1; }
            } else if (ty >= PANEL_Y) {
                int dy = ty - CTRL_Y; if (dy < 0) dy = -dy;
                int dpx = tx - PLAY_X;  if (dpx < 0) dpx = -dpx;
                if (dy <= 20) {
                    if (dpx <= 20) {
                        if (!playing) open_track(cur);
                        else paused = !paused;
                        ctrl = 1; listd = 1;
                    } else if (tx >= PREV_X - 18 && tx <= PREV_X + 18) {
                        next_track(-1); full = 1; recenter = 1;
                    } else if (tx >= NEXT_X - 18 && tx <= NEXT_X + 18) {
                        next_track(+1); full = 1; recenter = 1;
                    } else if (tx >= LOOP_X && tx < LOOP_X + LOOP_W) {
                        if (ty < PILL2_Y) loop_mode = (loop_mode + 1) % 3;
                        else              shuffle = !shuffle;
                        ctrl = 1;
                    } else if (tx >= LYR_X && tx < LYR_X + LYR_W) {
                        lyr_view = !lyr_view; topd = 1; ctrl = 1;
                    }
                }
            }
        }

        if (playing && track_ended) {
            track_ended = 0;
            if (loop_mode == LOOP_ONE) {
                open_track(cur);
            } else if (shuffle || cur + 1 < nfiles || loop_mode == LOOP_ALL) {
                next_track(+1);
            } else {
                close_track();         // end of list, loop off
            }
            full = 1; recenter = 1;
        }

        // ---- drawing that follows from what just happened
        int heavy = 0;
        if (full) {
            if (recenter) center_view_on_current();
            refresh_all();
            heavy = 1;
        } else {
            if (cover_changed || topd) { cover_changed = 0; pick_colours(); draw_top_full(); heavy = 1; }
            if (listd) { draw_list(); heavy = 1; }
            if (ctrl)  draw_controls();
            if (!topd && (listd || ctrl)) draw_progress();
            if (nfiles > 0 && !listd && !ctrl) {
                if (now - t_eq >= 150)   { t_eq = now;   eq_refresh(); }
                if (now - t_prog >= 500) { t_prog = now; draw_progress(); }
            }
        }

        // ---- at most one big job per pass, so a frame is never both decoding and drawing:
        unsigned fill = wr - rd;
        if (playing && fill < RING_FRAMES / 6) {             // 1. audio is running low: always first
            pump_budget = 2;
            pump();
            heavy = 1;
        }
        if (!heavy && nfiles > 0) {                          // 2. lyrics line / visualizer bars
            if (lyr_view) {
                if (playing && lyr_find(elapsed_ms()) != lyr_shown) { draw_lyrics(); heavy = 1; }
            } else if (now - t_viz >= viz_interval) {
                unsigned dtv = now - t_viz;
                if (dtv > 200) dtv = 200;
                t_viz = now;
                viz_snapshot();
                if (viz_update(dtv, viz_interval)) draw_viz();
                heavy = 1;
            }
        }
        if (!heavy && jactive) {                             // 3. a new picture, one slice at a time
            if (jp_step(64) == 1) {
                if (jp_pending) { cover_err = NULL; cover_cache_write(jp_cp, jp_sz, jp_hs); jp_pending = 0; }
                adopt_cover(2);
                cover_changed = 1;
            }
            heavy = 1;
        }
        if (combine || !heavy || fill < (RING_FRAMES * 3) / 8) {   // 4. otherwise decode music
            pump_budget = 1;
            pump();
        }
    }

    close_track();
    return 0;
}
