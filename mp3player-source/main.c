static void hsv(int h, int s, int v, u16 *out)       // h 0..359, s,v 0..255
{
    int region = h / 60, rem = (h % 60) * 255 / 60;
    int p = v * (255 - s) / 255;
    int q = v * (255 - s * rem / 255) / 255;
    int t = v * (255 - s * (255 - rem) / 255) / 255;
    int r, g, b;
    switch (region) {
        case 0:  r = v; g = t; b = p; break;
        case 1:  r = q; g = v; b = p; break;
        case 2:  r = p; g = v; b = t; break;
        case 3:  r = p; g = q; b = v; break;
        case 4:  r = t; g = p; b = v; break;
        default: r = v; g = p; b = q; break;
    }
    out[0] = (u16)r; out[1] = (u16)g; out[2] = (u16)b;
}

static inline u16 rgb3(const u16 *c) { return RGB(c[0], c[1], c[2]); }

static inline u16 lerp3(const u16 *a, const u16 *b, int t256)
{
    int r = (a[0] * (256 - t256) + b[0] * t256) >> 8;
    int g = (a[1] * (256 - t256) + b[1] * t256) >> 8;
    int bl = (a[2] * (256 - t256) + b[2] * t256) >> 8;
    return RGB(r, g, bl);
}

static unsigned name_hash(const char *s)
{
    unsigned h = 5381;
    while (*s) h = h * 33 + (unsigned char)*s++;
    return h;
}

static void pick_colours(void)
{
    static const u16 bg[3] = { 18, 18, 18 };
    int hue = nfiles > 0 ? (int)(name_hash(files[cur]) % 360) : 150;
    u16 base[3];
    hsv(hue, 160, 105, base);
    memcpy(top_base, base, sizeof base);
    hsv(hue, 175, 235, cov1);
    hsv((hue + 55) % 360, 190, 170, cov2);
    (void)bg;
}

// background colour of the top screen at row y (vertical gradient)
static u16 top_bg(int y)
{
    static const u16 bg[3] = { 18, 18, 18 };
    int t = y * 256 / 150;
    if (t > 256) t = 256;
    return lerp3(top_base, bg, t);
}

