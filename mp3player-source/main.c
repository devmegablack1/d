static void draw_cover(u16 *fb, int x0, int y0, int s)
{
    // gradient square with rounded corners
    for (int j = 0; j < s; j++) {
        for (int i = 0; i < s; i++) {
            int t = (i + j) * 256 / (2 * s);
            putpx(fb, x0 + i, y0 + j, lerp3(cov1, cov2, t));
        }
    }
    // round the corners by painting the screen background back
    int r = 8;
    for (int k = 0; k < r; k++) {
        int inset = r - circ_dx(r, r - k - 1);
        for (int i = 0; i < inset; i++) {
            putpx(fb, x0 + i, y0 + k, top_bg(y0 + k));
            putpx(fb, x0 + s - 1 - i, y0 + k, top_bg(y0 + k));
            putpx(fb, x0 + i, y0 + s - 1 - k, top_bg(y0 + s - 1 - k));
            putpx(fb, x0 + s - 1 - i, y0 + s - 1 - k, top_bg(y0 + s - 1 - k));
        }
    }
    // beamed music note, scaled for a 96px cover
    u16 w = RGB(255, 255, 255);
    int sc = s;                                   // base design is 96 wide
    int h1x = x0 + sc * 30 / 96, h1y = y0 + sc * 68 / 96;
    int h2x = x0 + sc * 62 / 96, h2y = y0 + sc * 60 / 96;
    int hr  = sc * 10 / 96;
    fill_circle(fb, h1x, h1y, hr, w);
    fill_circle(fb, h2x, h2y, hr, w);
    int sw = sc * 4 / 96 + 1;
    fill_rect(fb, h1x + hr - sw, y0 + sc * 28 / 96, sw, h1y - (y0 + sc * 28 / 96), w);
    fill_rect(fb, h2x + hr - sw, y0 + sc * 20 / 96, sw, h2y - (y0 + sc * 20 / 96), w);
    thick_line(fb, h1x + hr - sw, y0 + sc * 28 / 96, h2x + hr, y0 + sc * 20 / 96, sc * 7 / 96 + 1, w);
}

