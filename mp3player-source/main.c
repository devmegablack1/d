    const char *ll = loop_mode == LOOP_ONE ? "LOOP 1" : "LOOP";
    draw_pill(LOOP_X, PILL1_Y, ll, LOOP_W, loop_mode != LOOP_NONE);
    draw_pill(SHUF_X, PILL2_Y, "SHUFFLE", SHUF_W, shuffle);
